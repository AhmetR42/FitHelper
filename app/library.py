def youtube_url(name: str) -> str:
    query = "+".join(f"how to do {name}".lower().split())
    return f"https://www.youtube.com/results?search_query={query}"


def sync_library(session: Session) -> int:
    """Add or update every library exercise. Favourites stay as they are."""
    existing = {exercise.slug: exercise for exercise in session.exec(select(Exercise))}
    for entry in LIBRARY:
        exercise = existing.get(entry.slug) or Exercise(slug=entry.slug)
        exercise.sqlmodel_update(
            {
                "name": entry.name,
                "name_nl": entry.name_nl,
                "muscle": entry.muscle,
                "secondary": ",".join(entry.secondary),
                "equipment": entry.equipment,
                "level": entry.level,
                "unit": entry.unit,
                "demo": entry.demo,
                "steps_en": "\n".join(entry.steps_en),
                "steps_nl": "\n".join(entry.steps_nl),
                "tip_en": entry.tip_en,
                "tip_nl": entry.tip_nl,
            }
        )
        session.add(exercise)
    session.commit()
    return len(LIBRARY)
